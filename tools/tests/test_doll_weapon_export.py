    def claw_hand(self, finger_rows):
        """A cuffed hand with a six-bead brass plate and one talon per finger row; returns the palette indices."""
        h, w = 42, 64
        yy, xx = np.mgrid[0:h, 0:w]
        dots = np.full((h, w), -1, dtype=np.int16)
        self.outlined(dots, (xx >= 1) & (xx <= 5) & (yy >= 12) & (yy <= 27), self.IRON1)
        dots[(xx >= 6) & (xx <= 7) & (yy >= 11) & (yy <= 28)] = self.BRASS1
        palm = (xx >= 8) & (xx <= 36) & (yy >= 7) & (yy <= 32)
        for row in finger_rows:
            palm |= (xx >= 36) & (xx <= 54 + (row % 5)) & (yy >= row) & (yy <= row + 2)
        self.outlined(dots, palm, self.P2)
        plate = (xx >= 13) & (xx <= 27) & (yy >= 14) & (yy <= 25)
        dots[plate] = self.BRASS1
        for row in range(2):
            for col in range(3):
                y0, x0 = 16 + row * 5, 15 + col * 4
                dots[y0:y0 + 2, x0:x0 + 2] = self.GLASS
                dots[y0, x0] = self.PEARL1
        objects, *_ = ex.prepare_objects(self.draw(dots, 7.0), (1, 1), 1)
        return objects[0].idx

    def test_six_bead_plate_yields_six_ordered_beads(self):
        pitch = 7.0
        found, notes = ex.claw_anchors(self.claw_hand((9, 15, 21, 27, 33)), pitch)
        self.assertEqual([], notes)
        beads = found["beads"]
        self.assertEqual(6, len(beads))
        top, bottom = beads[:3], beads[3:]
        self.assertLess(max(b[1] for b in top) + 2 * pitch, min(b[1] for b in bottom))
        for row in (top, bottom):
            self.assertEqual(sorted(b[0] for b in row), [b[0] for b in row])
        self.assertLess(found["pivot"][0], 2 * pitch)
        self.assertEqual(ex.TALONS, len(found["tips"]))
        # the tips are ordered by angle around the pivot (image coordinates, y down): topmost first
        pivot = found["pivot"]
        angles = [math.atan2(t[1] - pivot[1], t[0] - pivot[0]) for t in found["tips"]]
        self.assertEqual(sorted(angles), angles)
        self.assertLess(found["tips"][0][1], found["tips"][-1][1])

