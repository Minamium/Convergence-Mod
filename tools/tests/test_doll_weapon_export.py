    def test_key_frames_align_on_the_shaft(self):
        pitch, cell = 8, (24, 20)
        sheet = np.full((cell[1] * 2, cell[0] * 2), -1, dtype=np.int16)
        lobes = (11, 7, 1, 7)
        offsets = ((3, 2), (9, 4), (5, 1), (7, 3))
        for frame, (half, (ox, oy)) in enumerate(zip(lobes, offsets)):
            cx, cy = (frame % 2) * cell[0] + ox, (frame // 2) * cell[1] + oy
            shaft_x = cx + 6
            sheet[cy + 7:cy + 13, shaft_x:shaft_x + 2] = self.BRASS1
            left = shaft_x + 1 - half // 2 - 1
            sheet[cy + 1:cy + 7, max(cx, left):shaft_x + 1 + half // 2 + 1] = self.BRASS1
            sheet[cy + 12, shaft_x:shaft_x + 2] = self.BRASS0
        objects, *_ = ex.prepare_objects(self.draw(sheet, pitch, 0), (2, 2), 4)
        frames, anchors = [], []
        for obj in objects:
            texels, _ = ex.reduce_cells(obj.idx, ex.object_grid(obj.size, pitch, 1), pitch * pitch)
            texels, _ = ex.trim(texels)
            frames.append(texels)
            anchors.append(ex.texel_extreme(texels, "bottom"))
        strip, meta = ex.strip(frames, anchors)
        width = meta["frame_size"][0]
        for i in range(4):
            frame = strip[:, i * width:(i + 1) * width]
            with self.subTest(frame=i):
                bottom = ex.texel_extreme(frame, "bottom")
                self.assertEqual(meta["anchor"][1], bottom[1])
                self.assertAlmostEqual(meta["anchor"][0], bottom[0], delta=0.5)

