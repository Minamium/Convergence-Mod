def written_files(root):
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file())


@unittest.skipUnless(HAVE_TOOLS, "numpy, scipy and Pillow are local asset-tool dependencies")
class WriteOutputsTests(unittest.TestCase):
    """What write_outputs puts where: the preview folder always, the repository only with write_repo."""
    REPO_PNG = "Assets/Textures/Items/DollWeapons/"
    ANCHORS = "Client/Encounters/FirstSeverance/Weapons/DollArtAnchors.g.cs"

    @staticmethod
    def fake_exporter():
        def output(name, runtime=True):
            texels = np.full((6, 8), -1, dtype=np.int16)
            texels[1:5, 1:7] = 6
            texels[1:5, 1] = 0
            info = {"k": 2, "png_size": [8, 6], "world_px": [16, 12]}
            return ex.Output(name, texels, info, {"centre": [4.0, 3.0]}, runtime=runtime)

        outputs = [output("Alpha"), output("Alpha_L"), output("Beta"), output("AlphaCheck", runtime=False)]
        return types.SimpleNamespace(outputs=outputs, report={"recipe_sha256": "0" * 64, "outputs": {}})

    def test_a_default_run_writes_only_the_preview_folder(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            ex.write_outputs(self.fake_exporter(), root / "preview", root=root)
            written = written_files(root)
            self.assertEqual([], [w for w in written if not w.startswith("preview/")])
            for name in ("Alpha.png", "Alpha_L.png", "Beta.png", "AlphaCheck.png", "report.json", "contact.png",
                         "anchors.png", "DollArtAnchors.g.cs.txt"):
                self.assertIn("preview/" + name, written)
            self.assertFalse((root / "Assets").exists())
            self.assertFalse((root / "Client").exists())

    def test_write_repo_adds_the_runtime_pngs_and_the_anchors(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            ex.write_outputs(self.fake_exporter(), root / "preview", write_repo=True, root=root)
            repo = [w for w in written_files(root) if not w.startswith("preview/")]
            # the preview-only output is never a runtime asset
            self.assertEqual(sorted([self.REPO_PNG + "Alpha.png", self.REPO_PNG + "Alpha_L.png", self.REPO_PNG + "Beta.png",
                                     self.ANCHORS]), repo)
            self.assertEqual((root / "preview" / "Alpha.png").read_bytes(), (root / self.REPO_PNG / "Alpha.png").read_bytes())
            anchors = (root / self.ANCHORS).read_bytes()
            self.assertEqual((root / "preview" / "DollArtAnchors.g.cs.txt").read_bytes(), anchors)
            self.assertIn(ex.GENERATED_HEADER, anchors.decode("utf-8"))

    def test_only_limits_the_repository_pngs_and_the_anchors_cover_what_has_landed(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
