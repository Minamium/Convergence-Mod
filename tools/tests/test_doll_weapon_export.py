        self.assertEqual([6, 6], registration["shift"])
        self.assertEqual(set(ex.PART_ORDER), set(parts), notes)
        self.assertTrue(all(not n.startswith("parts cut") for n in notes), notes)
        self.assertGreater(parts["sight"]["hole_area"], 0)
        self.assertGreaterEqual(parts["shroud"]["aspect"], 4)
        self.assertLess(parts["spring_housing"]["box"][0], parts["cylinder"]["box"][0])
        # the stub on the housing comes with it (the key seat stands there)
